//! `agg schema` — the JSON Schema of `agg.yaml`, DERIVED from the config types.
//!
//! The schema is `schemars`' reading of the very structs serde parses into ([`AggConfig`] and
//! everything under it), so it cannot drift from the parser: a new key is in the schema the moment
//! it is a field, and `#[serde(deny_unknown_fields)]` comes out as `additionalProperties: false`.
//!
//! The same schema also drives [`unknown_keys`], which finds EVERY misspelled key in a document at
//! once. serde stops at the first one; `agg check` must list them all.

use crate::core::config::AggConfig;
use crate::problem::{join, Problem};
use serde_json::Value as Json;
use serde_yaml::Value as Yaml;

/// The JSON Schema (draft 2020-12) for `agg.yaml`, stamped with the agg version that produced it.
pub fn config_schema() -> Json {
    let mut s = schemars::schema_for!(AggConfig).to_value();
    if let Some(o) = s.as_object_mut() {
        o.insert("title".into(), Json::from("agg.yaml"));
        o.insert("$comment".into(), Json::from(format!("generated by agg {}", env!("CARGO_PKG_VERSION"))));
    }
    s
}

/// Every key in `doc` that the schema does not allow, each with its dotted path and serde's own
/// wording (`unknown field `x`, expected one of …`), in document order.
///
/// Only the key structure is checked — types are serde's job, and serde reports them well. A value
/// whose shape matches no object in the schema (a string where a mapping goes) is not descended.
pub fn unknown_keys(doc: &Yaml) -> Vec<Problem> {
    let schema = config_schema();
    let mut out = Vec::new();
    walk(&schema, &schema, doc, "", &mut out);
    out
}

/// Check one YAML node against one schema node, recursing into mappings and sequences.
fn walk(root: &Json, node: &Json, v: &Yaml, path: &str, out: &mut Vec<Problem>) {
    match v {
        Yaml::Mapping(m) => {
            let Some(obj) = shape(root, node, "properties").or_else(|| shape(root, node, "additionalProperties")) else {
                return;
            };
            let props = obj.get("properties").and_then(Json::as_object);
            for (k, child) in m {
                let Some(key) = k.as_str() else { continue };
                let here = join(path, key);
                match (props.and_then(|p| p.get(key)), obj.get("additionalProperties")) {
                    (Some(s), _) => walk(root, s, child, &here, out),
                    (None, Some(Json::Bool(false))) => out.push(Problem::new(here, unknown_field(key, props))),
                    (None, Some(extra)) => walk(root, extra, child, &here, out),
                    (None, None) => {}
                }
            }
        }
        Yaml::Sequence(items) => {
            if let Some(item) = shape(root, node, "items").and_then(|o| o.get("items")) {
                for (i, child) in items.iter().enumerate() {
                    walk(root, item, child, &format!("{path}[{i}]"), out);
                }
            }
        }
        Yaml::Tagged(t) => walk(root, node, &t.value, path, out),
        _ => {}
    }
}

/// The schema object (this node, or one of its `anyOf`/`oneOf`/`allOf` branches, `$ref`s
/// followed) that carries `keyword` — i.e. the branch that describes a mapping or a list.
fn shape<'a>(root: &'a Json, node: &'a Json, keyword: &str) -> Option<&'a serde_json::Map<String, Json>> {
    let node = resolve(root, node);
    let obj = node.as_object()?;
    if obj.contains_key(keyword) {
        return Some(obj);
    }
    ["anyOf", "oneOf", "allOf"]
        .iter()
        .filter_map(|k| obj.get(*k).and_then(Json::as_array))
        .flatten()
        .find_map(|branch| shape(root, branch, keyword))
}

/// Follow a local `$ref` (`#/$defs/Name`) to its definition; any other node is returned as is.
fn resolve<'a>(root: &'a Json, node: &'a Json) -> &'a Json {
    match node.get("$ref").and_then(Json::as_str).and_then(|r| r.strip_prefix('#')) {
        Some(ptr) => root.pointer(ptr).map(|n| resolve(root, n)).unwrap_or(node),
        None => node,
    }
}

/// serde's message for a key `deny_unknown_fields` rejects, so `agg check` reads like startup.
fn unknown_field(key: &str, props: Option<&serde_json::Map<String, Json>>) -> String {
    let names: Vec<String> = props.map(|p| p.keys().map(|k| format!("`{k}`")).collect()).unwrap_or_default();
    match names.as_slice() {
        [] => format!("unknown field `{key}`, there are no fields"),
        [one] => format!("unknown field `{key}`, expected {one}"),
        many => format!("unknown field `{key}`, expected one of {}", many.join(", ")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn yaml(s: &str) -> Yaml {
        serde_yaml::from_str(s).expect("test yaml")
    }

    fn paths(doc: &str) -> Vec<String> {
        unknown_keys(&yaml(doc)).into_iter().map(|p| p.path).collect()
    }

    /// `deny_unknown_fields` must come out as `additionalProperties: false` on every struct, or the
    /// schema would accept the misspelled keys the parser refuses.
    #[test]
    fn every_config_struct_is_closed() {
        let s = config_schema();
        assert_eq!(s["additionalProperties"], Json::Bool(false), "the top level must be closed");
        for (name, def) in s["$defs"].as_object().expect("the schema has $defs") {
            if def.get("properties").is_some() {
                assert_eq!(def["additionalProperties"], Json::Bool(false), "`{name}` must be closed");
            }
        }
        assert_eq!(s["title"], "agg.yaml");
    }

    #[test]
    fn a_clean_document_has_no_unknown_keys() {
        let doc = "project: p\ndefaults: { agent: claude, isolation: sandbox }\njudges: { t: { timeout: 9 } }\n\
                   steps: { w: { readonly: [a] } }\nsequence:\n  steps: [w, { step: w, times: 2 }]\n  limits: { cost: 1.0 }\n";
        assert!(paths(doc).is_empty(), "{:?}", paths(doc));
    }

    /// The point of the walker: ALL of them, each located, in document order — through a map keyed
    /// by user names (`steps.<name>`), a list of mixed shapes, and an optional nested struct.
    #[test]
    fn every_unknown_key_is_found_with_its_path() {
        let doc = "project: p\nbogus: 1\ndefaults: { agnet: claude }\nsteps: { w: { judge_model: x } }\n\
                   sequence:\n  steps: [w, { step: w, tims: 2 }]\n  notify: { cmd: [], every: 1 }\n  limits: { wall_hours: 8 }\n";
        assert_eq!(
            paths(doc),
            [
                "bogus",
                "defaults.agnet",
                "steps.w.judge_model",
                "sequence.steps[1].tims",
                "sequence.notify.every",
                "sequence.limits.wall_hours"
            ]
        );
    }

    #[test]
    fn the_message_is_serdes_wording() {
        let p = &unknown_keys(&yaml("project: p\njudges: { t: { timeot: 1 } }\n"))[0];
        assert_eq!(p.path, "judges.t.timeot");
        assert_eq!(p.message, "unknown field `timeot`, expected one of `timeout`, `metric`, `score`, `max`, `min`");
        let p = &unknown_keys(&yaml("project: p\nwatchdog: { x: 1 }\n"))[0];
        assert!(p.message.starts_with("unknown field `x`, expected one of "), "{}", p.message);
    }

    /// A value of the wrong SHAPE is serde's to report; the walker must not invent key errors for it.
    #[test]
    fn a_wrongly_shaped_value_is_not_descended() {
        assert!(paths("project: p\ndefaults: \"claude\"\nsequence: { steps: [{ step: w }], limits: [1] }\n").is_empty());
    }

    #[test]
    fn unknown_field_wording_covers_every_arity() {
        assert_eq!(unknown_field("k", None), "unknown field `k`, there are no fields");
        let one: serde_json::Map<String, Json> = [("timeout".to_string(), Json::Null)].into_iter().collect();
        assert_eq!(unknown_field("k", Some(&one)), "unknown field `k`, expected `timeout`");
    }
}
