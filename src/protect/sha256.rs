//! SHA-256 (FIPS 180-4), streaming — the content hash behind the protected-path snapshot.
//!
//! Hand-rolled rather than a crate because it is ~80 lines of a frozen standard and agg's
//! dependency list is deliberately short. It must be a CRYPTOGRAPHIC hash, not `DefaultHasher`:
//! the worker chooses the bytes it writes, and a hash it can collide is a gate it can walk through.
//! The test vectors below are the NIST ones.

